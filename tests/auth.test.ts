import { afterAll, beforeAll, expect, it } from 'vitest';
import { PGlite } from '@electric-sql/pglite';
import { migrate } from '../src/server/db/migrate';
import { fixtureRuntime } from './helpers/runtime';
let db: PGlite;
let services: ReturnType<typeof fixtureRuntime>['owner'];
beforeAll(async () => { db = new PGlite(); await migrate(db); services = fixtureRuntime(db).owner; }, 60000);
afterAll(async () => { await db?.close(); });
it('Uses the Drizzle adapter on P2 tables for the complete database session lifecycle', async () => {
  const adapter = services.authAdapter;
  const user = await adapter.createUser!({ id: crypto.randomUUID(), name: 'Faisal Rahman', email: 'faisal@example.test', emailVerified: new Date(), image: null });
  expect(user.id).toMatch(/^[a-f0-9-]{36}$/);
  expect(user.emailVerified).toBeInstanceOf(Date);
  expect((await adapter.getUser!(user.id))?.email).toBe(user.email);
  expect((await adapter.getUserByEmail!(user.email))?.id).toBe(user.id);
  await adapter.linkAccount!({ userId: user.id, type: 'oidc', provider: 'google', providerAccountId: 'fixture_google_id', access_token: 'fixture_token' });
  expect((await adapter.getUserByAccount!({ provider: 'google', providerAccountId: 'fixture_google_id' }))?.id).toBe(user.id);
  const expires = new Date(Date.now() + 3600000);
  await adapter.createSession!({ userId: user.id, sessionToken: 'fixture_session_token', expires });
  expect((await adapter.getSessionAndUser!('fixture_session_token'))?.session.expires).toEqual(expires);
  expect((await adapter.getSessionAndUser!('fixture_session_token'))?.user).toMatchObject({ id: user.id, name: 'Faisal Rahman', email: 'faisal@example.test', image: null });
  expect((await adapter.getUserByAccount!({ provider: 'google', providerAccountId: 'fixture_google_id' }))?.email).toBe(user.email);
  const member = await services.sessionMember('fixture_session_token');
  expect(member).toMatchObject({ display_name: 'Faisal Rahman', roles: ['admin'], is_demo: false });
  await adapter.updateSession!({ sessionToken: 'fixture_session_token', expires: new Date(Date.now() - 1000) });
  expect(await services.sessionMember('fixture_session_token')).toBeNull();
  await adapter.updateUser!({ id: user.id, name: 'Faisal' });
  expect((await adapter.getUser!(user.id))?.name).toBe('Faisal');
  await adapter.deleteSession!('fixture_session_token');
  expect(await adapter.getSessionAndUser!('fixture_session_token')).toBeNull();
  expect(await adapter.getUser!(crypto.randomUUID())).toBeNull();
  expect(await adapter.getUserByEmail!('unknown@example.test')).toBeNull();
  expect(await adapter.getUserByAccount!({ provider: 'google', providerAccountId: 'unknown' })).toBeNull();
});
it('Refuses linking a demo member to Google and database identity insertion into a demo workspace', async () => {
  const ticket = await services.demo.start('ravi', null);
  const member = await services.demo.member(ticket);
  await expect(services.authAdapter.linkAccount!({ userId: member!.id, type: 'oidc', provider: 'google', providerAccountId: 'cannot_link' })).rejects.toThrow('User not found');
  await expect(db.query('INSERT INTO users (workspace_id,email) VALUES ($1,$2)', [ticket.sandbox,'ravi@example.test'])).rejects.toThrow('Demo authentication refused');
  expect((await db.query('SELECT * FROM users WHERE workspace_id=$1', [ticket.sandbox])).rows).toHaveLength(0);
  expect((await db.query('SELECT * FROM accounts WHERE workspace_id=$1', [ticket.sandbox])).rows).toHaveLength(0);
});
