import { expect,test } from '@playwright/test';
import { begin,fits } from '../fixtures/trust-browser';
for(const width of [360,390,1440])for(const locale of ['en','ar'] as const)test(`Recovery ${width} ${locale}`,async({page})=>{
  const m=await begin(page,width,locale),t=m.trust;
  await page.goto('/recovery');
  const detail=page.locator('.recovery-detail');
  await expect(detail.getByRole('heading',{name:'Review delivery note'})).toBeVisible();
  await expect(detail.getByRole('button')).toHaveCount(1);
  await detail.getByRole('button',{name:t.options.resolve_with_note}).click();
  await expect(detail.getByLabel(t.note)).toHaveAttribute('aria-invalid','true');
  await expect(detail.getByRole('alert')).toHaveText(t.noteRequired);
  await detail.getByLabel(t.note).fill('Imran checked the delivery');
  await page.route('**/api/recovery/*/actions',route=>route.fulfill({status:503,json:{}}),{times:1});
  await detail.getByRole('button',{name:t.options.resolve_with_note}).click();
  await expect(detail.getByRole('alert')).toContainText(t.error);
  await detail.getByRole('button',{name:t.retry}).click();
  await expect(page.getByRole('status')).toHaveText(t.done);
  await expect(detail.getByRole('heading',{name:'Retry delivery work'})).toBeVisible();
  await detail.getByRole('button',{name:t.options.retry_now}).click();
  await expect(detail.getByRole('heading',{name:'Check sent mail'})).toBeVisible();
  await detail.getByRole('button',{name:t.options.reconcile}).click();
  await expect(detail.getByRole('heading',{name:'Cancel remaining work'})).toBeVisible();
  await detail.getByRole('button',{name:t.options.cancel_remaining}).click();
  await expect(detail).toContainText(t.empty);
  await fits(page,width);
});
for(const width of [390,1440])test(`Reversible work Undo ${width}`,async({page})=>{
  const m=await begin(page,width,'en'),t=m.trust;
  const runs=await(await page.request.get('/api/client')).json();
  const harbor=runs.runs.find((r:{name:string})=>r.name.startsWith('Harbor'));
  await page.goto(`/runs/${harbor.id}`);
  const approval=page.locator('.approval-card').filter({hasNot:page.locator('.stale-notice')});
  await approval.getByRole('button',{name:m.screens.approve,exact:true}).click();
  await approval.getByRole('button',{name:m.screens.execute,exact:true}).click();
  await expect(page.locator('.run-detail > p').first()).toHaveText(m.screens.statuses.ready,{timeout:30000});
  await page.goto('/recovery');
  await page.getByLabel(t.note).fill('Imran checked the delivery');
  await page.locator('.recovery-detail').getByRole('button',{name:t.options.resolve_with_note}).click();
  const toast=page.locator('.undo-toast');
  await expect(toast.getByRole('button',{name:t.undo,exact:true})).toBeVisible();
  const toastBox=(await toast.boundingBox())!,detailBox=(await page.locator('.recovery-detail').boundingBox())!;
  expect(toastBox.y+toastBox.height).toBeLessThanOrEqual(detailBox.y);
  const reversal=page.waitForResponse(response=>response.url().endsWith('/undo'));
  await toast.getByRole('button',{name:t.undo,exact:true}).click();
  const response=await reversal;expect(response.status()).toBe(201);expect((await response.json()).approval.kind).toBe('reversal');
  await expect(page.locator('.screen > p[role="status"]')).toHaveText(t.undoReady);
  await page.clock.install();
  await page.locator('.recovery-detail').getByRole('button',{name:t.options.retry_now}).click();
  await expect(toast).toBeVisible();
  await page.clock.fastForward(8001);
  await expect(toast).toHaveCount(0);
  await fits(page,width);
});
