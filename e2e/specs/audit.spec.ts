import { expect,test } from '@playwright/test';
import { begin,fits } from '../fixtures/trust-browser';
for(const width of [360,390,1440])for(const locale of ['en','ar'] as const)test(`Audit ${width} ${locale}`,async({page})=>{
  const m=await begin(page,width,locale,'faisal'),t=m.trust;
  const runs=await(await page.request.get('/api/client')).json();
  const check=await page.request.post('/api/demo/backend-check',{data:{runId:runs.runs[0].id}});expect(check.status()).toBe(200);
  await page.goto('/audit-log');
  await expect(page.getByText(t.chainOk,{exact:true})).toBeVisible();
  await page.getByLabel(t.actor,{exact:true}).fill('Ravi');
  await page.getByRole('combobox',{name:t.action,exact:true}).selectOption('approve_plan');
  await page.getByRole('combobox',{name:t.outcome,exact:true}).selectOption('denied');
  await page.getByLabel(t.run,{exact:true}).fill(runs.runs[0].id);
  const today=new Date().toISOString().slice(0,10);
  await page.getByLabel(t.date,{exact:true}).fill(today);
  await page.getByRole('button',{name:t.apply}).click();
  await expect(page).toHaveURL(/actor=Ravi&action=approve_plan&outcome=denied&run=.+&date=/);
  await page.reload();
  await expect(page.locator('.denied-row')).toHaveCount(1);
  await expect(page.locator('.audit-rows')).toContainText('Ravi Menon');
  await expect(page.getByLabel(t.actor,{exact:true})).toHaveValue('Ravi');
  await fits(page,width);
  await page.route('**/api/audit',route=>route.fulfill({status:503,json:{}}),{times:1});
  await page.reload();
  await expect(page.locator('main').getByRole('alert')).toContainText(t.error);
  await expect(page.getByText(t.chainOk,{exact:true})).toHaveCount(0);
  await page.getByRole('button',{name:t.retry,exact:true}).click();
  await expect(page.getByText(t.chainOk,{exact:true})).toBeVisible();
  await page.getByRole('combobox',{name:m.shell.persona}).selectOption('ravi');
  await expect(page).toHaveURL(/\/today/);
  await page.goto('/audit-log');
  await expect(page.locator('main').getByRole('alert')).toContainText(t.refused);
  await expect(page.getByText(t.chainOk,{exact:true})).toHaveCount(0);
  expect((await page.request.get('/api/audit')).status()).toBe(403);
});
